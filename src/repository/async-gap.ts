/**
 * 실제 데이터베이스라면 read 와 write 사이에 네트워크 왕복이 존재한다.
 * 인메모리 구현은 그 틈을 인위적으로 흉내 내어, "읽은 뒤 다른 트랜잭션이
 * 끼어들 수 있는" 상황을 재현한다. 이 틈이 없으면 낙관적 잠금의 재시도
 * 로직이 테스트에서 전혀 실행되지 않는다(자바스크립트 단일 스레드 특성상
 * await 지점이 없으면 인터리빙이 생기지 않기 때문).
 */
// 매크로태스크 타이머(setTimeout) 대신 마이크로태스크로 틈을 만든다.
// 이렇게 해야 만료 테스트에서 사용하는 vi.useFakeTimers() 와 충돌하지 않고,
// 200건 동시 예약 테스트도 실제 타이머 지연 없이 빠르게 끝난다.
export function ioGap(): Promise<void> {
  return Promise.resolve().then(() => undefined);
}
